impl Labels {
    pub(super) fn api_truncated(&self, entries: usize) -> String {
        self.api_truncated_template
            .replace("{}", &entries.to_string())
    }

    pub(super) fn analyzed_files_note(&self, analyzed: usize, total: usize) -> String {
        self.analyzed_files_note_template
            .replace("{analyzed}", &analyzed.to_string())
            .replace("{total}", &total.to_string())
    }
}

